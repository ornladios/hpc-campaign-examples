def _write_prefixed_source(path: Path, time_values: list[float] | None = None) -> None:
    """Write self-describing MHD steps using code-specific names."""
    y, x = np.mgrid[0:3, 0:4]
    fields = {
        "sim_rho": 1.0 + x + y,
        "sim_pressure": 2.0 + x * y,
        "sim_bx": x.astype(np.float64),
        "sim_by": y.astype(np.float64),
    }
    resolved_times = [0.0] if time_values is None else time_values
    with Stream(str(path), "w") as stream:
        for time_value in resolved_times:
            stream.begin_step()
            for name, values in fields.items():
                data = np.asarray(values, dtype=np.float64)
                stream.write(name, data, data.shape, [0, 0], data.shape)
            time_array = np.asarray([time_value], dtype=np.float64)
            stream.write("time", time_array, time_array.shape, [0], [1])
            stream.end_step()


def _register_datasets(manager: Manager, root: Path, paths: list[Path]) -> None:
    """Register payloads using the run-relative names consumed by PROV."""
    for path in paths:
        manager.data(str(path), name=path.relative_to(root).as_posix())


def _logical_entities(document) -> list[ProvEntity]:
    return [
        record
        for record in document.get_records(ProvEntity)
        if HPC["LogicalVariable"] in record.get_asserted_types()
    ]


def test_ingest_records_simulation_derived_fields_and_statistics(tmp_path: Path) -> None:
    """The graph must preserve simulation generation and exact lineage."""
    run_dir = tmp_path / "run-001"
    run_dir.mkdir()
    source = run_dir / "output.bp"
    derived = run_dir / "analysis.bp"
    statistics = run_dir / "output_stats.bp"
    _write_prefixed_source(source)
    create_derived_dataset(source, derived)
    create_statistics_dataset(source, statistics)
    second_source = tmp_path / "run-002" / "output.bp"
    second_source.parent.mkdir()
    _write_prefixed_source(second_source)

    manager = Manager(archive="mhd.aca", campaign_store=str(tmp_path))
    manager.open(create=True, truncate=True)
    try:
        manager.set_schema(SCHEMA_PATH)
        datasets = [source, derived, statistics, second_source]
        _register_datasets(manager, tmp_path, datasets)
        index = record_campaign_provenance(manager, datasets, tmp_path)
        assert set(manager.validate_schema()["instances"]) == {"run-001", "run-002"}
        dataset_names = {item.name for item in manager.info().datasets.values()}
        assert "__provenance_plan_adios_derived_variables.py" in dataset_names
        assert "__provenance_plan_adios_stats.py" in dataset_names
        document = active_document(manager)

        pressure = index.by_definition[("run-001", "pressure")].reference
        magnetic_x = index.by_definition[("run-001", "magnetic_field_x")].reference
        magnetic_y = index.by_definition[("run-001", "magnetic_field_y")].reference
        divergence = index.by_definition[("run-001", "magnetic_field_divergence")].reference
        pressure_mean = index.by_definition[("run-001", "pressure_mean")].reference

        # Source variables are declared first, then generated by the root
        # Simulation Activity that represents this solver run.
        pressure_generation = [
            record
            for record in document.get_records(ProvGeneration)
            if record.args[0] == pressure
        ]
        assert len(pressure_generation) == 1
        assert pressure_generation[0].args[1] == index.simulations["run-001"]
        simulation = document.get_record(index.simulations["run-001"])[0]
        assert HPC["Simulation"] in simulation.get_asserted_types()

        # div(B) is derived from both vector components. This also exercises
        # campaign relationship roles containing underscores.
        divergence_parents = {
            record.args[1]
            for record in document.get_records(ProvDerivation)
            if record.args[0] == divergence
        }
        assert divergence_parents == {magnetic_x, magnetic_y}

        # Statistics remain first-class logical variables with their own
        # Activity instead of being unstructured metadata on the source.
        mean_parents = {
            record.args[1]
            for record in document.get_records(ProvDerivation)
            if record.args[0] == pressure_mean
        }
        assert mean_parents == {pressure}
        mean_entity = next(record for record in _logical_entities(document) if record.identifier == pressure_mean)
        assert mean_entity.get_attribute(HPC["units"]) == {"normalized pressure"}

        qoi_activities = [
            record
            for record in document.get_records(ProvActivity)
            if HPC["QuantityOfInterest"] in record.get_asserted_types()
        ]
        assert qoi_activities
    finally:
        manager.close()


def test_visualization_records_all_inputs_and_sequence_manifest(tmp_path: Path) -> None:
    """A streamline sequence must trace to vector and background variables."""
    run_dir = tmp_path / "run-001"
    run_dir.mkdir()
    source = run_dir / "output.bp"
    _write_prefixed_source(source)

    manager = Manager(archive="mhd.aca", campaign_store=str(tmp_path))
    manager.open(create=True, truncate=True)
    try:
        manager.set_schema(SCHEMA_PATH)
        _register_datasets(manager, tmp_path, [source])
        index = record_campaign_provenance(manager, [source], tmp_path)

        semantic_variables = {
            "streamline_by": ("sim_bx", "sim_by"),
            "color_by": "sim_pressure",
        }
        sequence_short_name = "magnetic_streamlines"
        add_visualization(
            manager=manager,
            dataset_name="run-001/output.bp",
            variable=sequence_short_name,
            vis_type="streamlines",
            name=sequence_short_name,
            steps=[0],
            images=[TINY_PNG],
            replace=False,
            thumbnail_step=0,
            semantic_kwargs=semantic_variables,
        )
        sequence_name = visualization_sequence_name("run-001/output.bp", sequence_short_name)
        recorder = VisualizationProvenanceRecorder(
            manager,
            Path(__file__).parents[1] / "scripts" / "render_adios_visualizations_to_campaign.py",
        )
        output = recorder.record(
            source_dataset="run-001/output.bp",
            sequence_name=sequence_name,
            vis_type="streamlines",
            semantic_kwargs=semantic_variables,
            steps=[0],
            rendering_parameters={"colormap": "viridis"},
        )

        # Scalar heatmaps use color_by rather than a generic primary role; the
        # sequence collection remains a distinct product from the input variable.
        add_visualization(
            manager=manager,
            dataset_name="run-001/output.bp",
            variable="sim_pressure",
            vis_type="heatmap",
            name="pressure_heatmap",
            steps=[0],
            images=[TINY_PNG],
            replace=False,
            thumbnail_step=0,
            semantic_kwargs={"color_by": "sim_pressure"},
        )
        pressure_result = recorder.record(
            source_dataset="run-001/output.bp",
            sequence_name=visualization_sequence_name("run-001/output.bp", "pressure_heatmap"),
            vis_type="heatmap",
            semantic_kwargs={"color_by": "sim_pressure"},
            steps=[0],
            rendering_parameters={"colormap": "viridis"},
        )
        document = active_document(manager)

        expected_inputs = {
            index.by_definition[("run-001", "magnetic_field_x")].reference,
            index.by_definition[("run-001", "magnetic_field_y")].reference,
            index.by_definition[("run-001", "pressure")].reference,
        }
        actual_inputs = {
            record.args[1]
            for record in document.get_records(ProvDerivation)
            if record.args[0] == output.outputs["image_sequence"]
        }
        assert actual_inputs == expected_inputs

        output_entity = document.get_record(output.outputs["image_sequence"])[0]
        assert HPC["VisualizationSequence"] in output_entity.get_asserted_types()
        assert HPC["ImageSequence"] in output_entity.get_asserted_types()
        assert output_entity.get_attribute(HPC["sequenceName"]) == {sequence_name}

        pressure_sequence_name = visualization_sequence_name("run-001/output.bp", "pressure_heatmap")
        pressure_entity = document.get_record(pressure_result.outputs["image_sequence"])[0]
        assert HPC["VisualizationSequence"] in pressure_entity.get_asserted_types()
        assert pressure_entity.get_attribute(HPC["sequenceName"]) == {pressure_sequence_name}
        assert set(manager.validate_schema()["instances"]) == {"run-001"}
    finally:
        manager.close()


@pytest.mark.skipif(not hasattr(Manager, "video"), reason="requires a video-capable hpc-campaign checkout")
def test_video_sequence_records_semantic_roles_time_and_provenance(tmp_path: Path) -> None:
    """Video metadata must retain semantic variable roles and time lineage."""
    run_dir = tmp_path / "run-001"
    run_dir.mkdir()
    source = run_dir / "output.bp"
    movie = tmp_path / "pressure.mp4"
    movie.write_bytes(b"opaque mp4 payload")
    _write_prefixed_source(source, time_values=[0.0, 0.25, 1.0])

    manager = Manager(archive="mhd.aca", campaign_store=str(tmp_path))
    manager.open(create=True, truncate=True)
    try:
        manager.set_schema(SCHEMA_PATH)
        _register_datasets(manager, tmp_path, [source])
        index = record_campaign_provenance(manager, [source], tmp_path)
        source_dataset = "run-001/output.bp"
        sequence_name = visualization_sequence_name(source_dataset, "pressure_movie")
        semantic_kwargs = {"color_by": "sim_pressure"}
        manager.video(
            movie,
            name=f"{sequence_name}.mp4",
            variables=visualization_variable_specs(semantic_kwargs, source_dataset),
            vis_type="heatmap",
            source_dataset=source_dataset,
            sequence_name=sequence_name,
            time_variable=(source_dataset, "time"),
            time_indices=[0, 1, 2],
            frame_count=3,
            store=True,
        )

        info = manager.info(list_replicas=True, list_files=True)
        sequence = next(item for item in info.visualization_sequences.values() if item.name == sequence_name)
        assert [(item.name, item.role, item.source_dataset_name) for item in sequence.variables] == [
            ("sim_pressure", "color-by", source_dataset)
        ]
        assert sequence.items[0].item_type == "VIDEO"
        assert sequence.items[0].file_format == "VIDEO"
        item_metadata = json.loads(sequence.items[0].metadata or "{}")
        assert item_metadata["time_values"] == [0.0, 0.25, 1.0]
        assert item_metadata["time_source"]["indices"] == [0, 1, 2]

        recorder = VisualizationProvenanceRecorder(
            manager,
            Path(__file__).parents[1] / "scripts" / "render_adios_visualizations_to_campaign.py",
        )
        result = recorder.record(
            source_dataset=source_dataset,
            sequence_name=sequence_name,
            vis_type="heatmap",
            semantic_kwargs=semantic_kwargs,
            steps=[0, 1, 2],
            rendering_parameters={"frame_rate": 10.0},
            output_variable="video",
        )
        document = active_document(manager)
        output = result.outputs["video"]
        output_parents = {
            record.args[1]
            for record in document.get_records(ProvDerivation)
            if record.args[0] == output
        }
        assert output_parents == {index.by_definition[("run-001", "pressure")].reference}
        output_entity = document.get_record(output)[0]
        assert HPC["VisualizationSequence"] in output_entity.get_asserted_types()
        assert HPC["VideoSequence"] in output_entity.get_asserted_types()
        assert set(manager.validate_schema()["instances"]) == {"run-001"}
    finally:
        manager.close()


def test_scalar_field_sequence_records_items_and_provenance(tmp_path: Path) -> None:
    """A scalar-field sequence must register raw fields and source lineage."""
    run_dir = tmp_path / "run-001"
    run_dir.mkdir()
    source = run_dir / "output.bp"
    _write_prefixed_source(source)

    manager = Manager(archive="mhd.aca", campaign_store=str(tmp_path))
    manager.open(create=True, truncate=True)
    try:
        manager.set_schema(SCHEMA_PATH)
        _register_datasets(manager, tmp_path, [source])
        index = record_campaign_provenance(manager, [source], tmp_path)
        field = np.arange(12, dtype=np.float64).reshape(3, 4)

        add_scalar_field_sequence(
            manager,
            dataset_name="run-001/output.bp",
            variable="sim_pressure",
            vis_type="heatmap",
            name="pressure_scalar_field",
            steps=[0],
            arrays=[field],
            replace=False,
            dtype="float32",
        )
        sequence_name = visualization_sequence_name(
            "run-001/output.bp",
            "pressure_scalar_field",
        )
        recorder = VisualizationProvenanceRecorder(
            manager,
            Path(__file__).parents[1] / "scripts" / "add_scalar_fields_to_campaign.py",
        )
        result = recorder.record(
            source_dataset="run-001/output.bp",
            sequence_name=sequence_name,
            vis_type="heatmap",
            semantic_kwargs={"color_by": "sim_pressure"},
            steps=[0],
            rendering_parameters={"scalar_fields": True, "dtype": "float32"},
        )

        info_data = manager.info(list_replicas=True, list_files=True)
        sequence_info = next(
            sequence
            for sequence in info_data.visualization_sequences.values()
            if sequence.name == sequence_name
        )
        assert sequence_info.items[0].item_type == "SCALAR_FIELD"
        scalar_dataset = next(
            dataset
            for dataset in info_data.datasets.values()
            if dataset.name == sequence_info.items[0].dataset_name
        )
        assert scalar_dataset.file_format == "SCALAR_FIELD"
        assert scalar_dataset.metadata["shape"] == [3, 4]
        assert scalar_dataset.metadata["dtype"] == "float32"

        document = active_document(manager)
        expected_pressure = index.by_definition[("run-001", "pressure")].reference
        assert set(result.outputs) == {"frame_0"}
        actual_inputs = {
            record.args[1]
            for record in document.get_records(ProvDerivation)
            if record.args[0] == result.outputs["frame_0"]
        }
        assert actual_inputs == {expected_pressure}
        assert HPC["Dataset"] in document.get_record(result.outputs["frame_0"])[0].get_asserted_types()
        assert set(manager.validate_schema()["instances"]) == {"run-001"}
    finally:
        manager.close()
